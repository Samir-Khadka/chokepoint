"""PR body generator (plan Section 7: anatomy of a Chokepoint PR).

A fix PR must be safe to review in five minutes. The body states
the outcome in the title, shows the chain it breaks in plain
language, shows the smallest possible diff, names what could
break, states the validation result, gives the exact re-scan that
will run after merge, and notes the revert. It also says plainly
that Chokepoint never merges its own PRs — human approval is the
merge.
"""

from __future__ import annotations

from ..paths.patterns import Path
from ..ranking.candidates import NOT_A_TF_CHANGE
from .generate import GeneratedFix


def _path_line(path: Path) -> str:
    nodes = " → ".join(node.label for node in path.nodes)
    return f"- {path.pattern}: {nodes} (to {path.crown_jewel.label})"


def render_pr_body(generated: GeneratedFix, account_id: str) -> str:
    """Markdown PR body for a validated fix."""
    cand = generated.candidate
    validation = generated.validation
    jewels = sorted({p.crown_jewel.label for p in validation.removed_paths})
    # The candidate's explanation was written for the ranking (Phase 3),
    # where the fix was only a graph removal. This PR implements it as a
    # Terraform change, so that sentence is replaced, not repeated.
    explanation = cand.explanation.replace(
        NOT_A_TF_CHANGE,
        " This PR implements that removal as a Terraform change — see the diff below.",
    )
    lines = [
        f"# {cand.title} — removes {generated.measured_paths_removed} "
        f"attack path(s) to {', '.join(jewels)}",
        "",
        "## Summary",
        "",
        explanation,
        "",
        f"Template: `{generated.template_name}`. Change: {generated.summary}. "
        "This PR was generated by Chokepoint in dry-run mode from the "
        "demo fixture. No infrastructure was changed to produce it, "
        "and merging it is a human decision.",
        "",
    ]
    if generated.note:
        lines += [generated.note, ""]
    lines += [
        "## The attack paths this breaks",
        "",
    ]
    for path in validation.removed_paths:
        lines.append(_path_line(path))
    lines += [
        "",
        "## The change",
        "",
        "Smallest possible diff — one policy narrowed, one public "
        "grant removed, one trust condition dropped. Never a refactor.",
        "",
        "```diff",
        generated.diff.rstrip("\n"),
        "```",
        "",
        "## Before / after",
        "",
        f"- Attack paths before: **{validation.before_count}**",
        f"- Attack paths after: **{validation.after_count}**",
        f"- Paths removed: **{validation.paths_removed}**",
        f"- New paths introduced: **{len(validation.new_paths)}**",
    ]
    if validation.after_paths:
        lines += [
            "",
            "Paths that survive this fix (each needs its own fix):",
            "",
        ]
        for path in validation.after_paths:
            lines.append(_path_line(path))
    lines += [
        "",
        "## What could break",
        "",
        cand.what_could_break,
        "",
        "## Validation",
        "",
        "The fix was validated before this PR was generated: path "
        "finding was re-run on the graph with the fix applied. "
        f"{validation.reason}.",
        "",
        "Verification plan after merge — re-scan the account and "
        "expect the after-count:",
        "",
        "```bash",
        "python -m chokepoint scan --demo",
        f"# expected: {validation.after_count} attack path(s)",
        "```",
        "",
        "## Revert",
        "",
        "This PR is its own revert: reverting it restores the prior "
        "policy exactly.",
        "",
        "## Review",
        "",
        "Chokepoint never merges its own PRs. Review before merging. "
        f"Generated from account {account_id or '(demo)'} in dry-run mode.",
        "",
    ]
    return "\n".join(lines)
